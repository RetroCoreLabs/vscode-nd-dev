using System;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Collections.Generic;
using System.Linq;
using NDGen.Core;
using NDGen.Core.Models;

namespace NDGen.Generators
{
    /// <summary>
    /// Writes codegen outputs into the VS Code extension project:
    /// <c>src/generated/generatedData.ts</c> and <c>src/generated/ndasm.tmLanguage.json</c>.
    /// Static sources (TypeScript, manifest, config) live in that folder and are edited in the repo.
    /// </summary>
    public class VSCodeExtensionGenerator : BaseGenerator
    {        
        private const string AUTOGENERATED_HEADER = @"// =============================================
// THIS FILE IS AUTOGENERATED - DO NOT EDIT
// Generated by ND-100 Language Extension Generator
// =============================================

";
        private readonly JsonSerializerOptions _jsonSerializerOptions = new JsonSerializerOptions { WriteIndented = true };

        /// <summary>
        /// Initializes a new instance of the VSCodeExtensionGenerator class.
        /// </summary>
        /// <param name="outputPath">Root of the extension project (e.g. repo <c>extension/</c>).</param>
        /// <param name="loader">The DefinitionLoader used to load instruction and register definitions.</param>
        public VSCodeExtensionGenerator(string outputPath, DefinitionLoader loader)
            : base(outputPath, loader)
        {
        }

        /// <summary>
        /// Writes generated artifacts under <c>src/generated/</c>. Expects static extension files to already exist.
        /// </summary>
        public override void Generate()
        {
            Console.WriteLine($"Generating VS Code extension artifacts in '{OutputPath}'...");

            if (!File.Exists(Path.Combine(OutputPath, "package.json")))
            {
                throw new InvalidOperationException(
                    $"VS Code extension project not found at '{OutputPath}' (missing package.json).");
            }

            Directory.CreateDirectory(Path.Combine(OutputPath, "out"));

            GenerateDataFile(OutputPath);
            GenerateTextMateGrammar(OutputPath);

            Console.WriteLine($"VS Code codegen finished at {OutputPath}");
        }

        private void GenerateDataFile(string outDIR)
        {
            Console.WriteLine("Using hard-coded template for data file generation...");
            
            // The hard-coded template is a simple version of the template file
            var templateContent = @"
// =============================================
// THIS FILE IS AUTOGENERATED - DO NOT EDIT
// Generated by ND-100 Language Extension Generator
// =============================================

import { InstructionData, RegisterData } from './interfaces';

// This will be replaced with the actual instruction data
export const instructionData: InstructionData = {{INSTRUCTION_DATA}};

// This will be replaced with the actual register data
export const registerData: RegisterData = {{REGISTER_DATA}}; 
";
            
            // Generate the instruction data
            var instructionData = Loader.GetInstructions().ToDictionary(
                i => i.Name.ToUpper(),
                i => new
                {
                    i.Name,
                    i.Opcode,
                    i.Format,
                    Description = ProcessAsciiTables(i.Description),
                    i.GeneratedBitFormat,
                    i.Category,
                    i.InstructionClass,
                    DetailedDescription = ProcessAsciiTables(i.DetailedDescription ?? string.Empty),
                    Privilege = i.Privilege.ToString().ToLower(),
                    FlagsAffected = i.FlagsAffected ?? new List<string>(),
                    Operands = i.Operands?.Select(op => new 
                    {
                        op.Name,
                        op.Type,
                        op.Description,
                        op.Bits,
                        EnumOptions = op.Type == "enum" && op.Enum != null 
                            ? op.Enum.Select(e => new { e.Name, e.Value, e.Description }).ToList() 
                            : null
                    }).ToList(),
                    Visualization = GenerateInstructionVisualization(i)
                }
            );

            var registerData = Loader.GetCpuDefinition().Metadata.Registers.ToDictionary(
                r => r.Name.ToUpper(),
                r => new
                {
                    r.Name,
                    r.Size,
                    r.Description,
                    r.Type,
                    Bits = r.Bits?.Select(b => new { b.Name, b.Description, b.Position, b.Size }).ToArray() ?? Array.Empty<object>()
                }
            );
            
            // Replace the placeholders with the actual data
            var content = templateContent
                .Replace("{{INSTRUCTION_DATA}}", JsonSerializer.Serialize(instructionData, _jsonSerializerOptions))
                .Replace("{{REGISTER_DATA}}", JsonSerializer.Serialize(registerData, _jsonSerializerOptions));
            
            // Add the autogenerated header
            content = AUTOGENERATED_HEADER + content;
            
            var outputFile = Path.Combine(outDIR, "src", "generated", "generatedData.ts");
            Directory.CreateDirectory(Path.GetDirectoryName(outputFile)!);
            File.WriteAllText(outputFile, content);
            
            Console.WriteLine($"Generated data file at {outputFile}");
        }

        /// <summary>
        /// Process ASCII table tags in description text, formatting them appropriately for VS Code display
        /// </summary>
        private string ProcessAsciiTables(string text)
        {
            if (string.IsNullOrEmpty(text))
                return text;

            // Process ASCII tables - for VS Code, we'll keep them as pre-formatted text but remove the tags
            if (text.Contains("<ascii-table>") && text.Contains("</ascii-table>"))
            {
                var regex = new System.Text.RegularExpressions.Regex("<ascii-table>(.*?)</ascii-table>", 
                    System.Text.RegularExpressions.RegexOptions.Singleline);
                
                return regex.Replace(text, match => 
                {
                    var tableContent = match.Groups[1].Value;
                    // For VS Code, simply preserve the content without the tags as pre-formatted text
                    return tableContent;
                });
            }

            return text;
        }

        private string GenerateInstructionVisualization(InstructionDefinition inst)
        {
            // If the instruction has an instruction class, use its operands
            if (!string.IsNullOrEmpty(inst.InstructionClass))
            {
                var instructionClass = Loader.GetCpuDefinition().Metadata.InstructionClasses
                    .FirstOrDefault(ic => ic.Name == inst.InstructionClass);
                    
                if (instructionClass?.Operands != null)
                {
                    return instructionClass.GeneratedBitFormat;
                }
            }

            // Use pre-generated bit format instead of generating it again
            return inst.GeneratedBitFormat ?? string.Empty;
        }

        private void GenerateTextMateGrammar(string extensionPath)
        {
            Console.WriteLine("Generating TextMate grammar...");
            
            var syntaxesDir = Path.Combine(extensionPath, "src/generated");
            Directory.CreateDirectory(syntaxesDir);
            
            GenerateTextMateGrammarDynamically(syntaxesDir);
        }

        // Keep this method since it's truly dynamic and uses data from the loader
        // Generate the file "syntaxes/ndasm.tmLanguage.json"
        private void GenerateTextMateGrammarDynamically(string syntaxesDir)
        {
            // Get all instructions from the definition
            var instructions = Loader.GetInstructions().Select(i => i.Name).ToList();
            var registers = Loader.GetCpuDefinition().Metadata.Registers.Select(r => r.Name).ToList();
            
            // Define grammar for syntax highlighting
            var grammar = new
            {
                name = "ND-100 Assembly",
                scopeName = "source.ndasm",
                fileTypes = new[] { "asm", "s" },
                patterns = new[]
                {
                    new { include = "#comment" },
                    new { include = "#instruction" },
                    new { include = "#register" },
                    new { include = "#literal" },
                    new { include = "#directive" }
                },
                repository = new
                {
                    comment = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "comment.line.semicolon.ndasm",
                                match = ";.*$"
                            }
                        }
                    },
                    instruction = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "keyword.instruction.ndasm",
                                match = $"\\b(?i)({string.Join("|", instructions)})\\b"
                            }
                        }
                    },
                    register = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "variable.register.ndasm",
                                match = $"\\b(?i)({string.Join("|", registers)})\\b"
                            }
                        }
                    },
                    literal = new
                    {
                        patterns = new object[]
                        {
                            new
                            {
                                name = "constant.numeric.hex.ndasm",
                                match = "\\b0x[0-9A-Fa-f]+\\b"
                            },
                            new
                            {
                                name = "constant.numeric.binary.ndasm",
                                match = "\\b0b[01]+\\b"
                            },
                            new
                            {
                                name = "constant.numeric.decimal.ndasm",
                                match = "\\b[0-9]+\\b"
                            },
                            new
                            {
                                name = "string.quoted.double.ndasm",
                                begin = "\"",
                                end = "\"",
                                patterns = new[]
                                {
                                    new
                                    {
                                        name = "constant.character.escape.ndasm",
                                        match = "\\\\."
                                    }
                                }
                            },
                            new
                            {
                                name = "string.quoted.single.ndasm",
                                begin = "'",
                                end = "'",
                                patterns = new[]
                                {
                                    new
                                    {
                                        name = "constant.character.escape.ndasm",
                                        match = "\\\\."
                                    }
                                }
                            }
                        }
                    },
                    directive = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "keyword.control.directive.ndasm",
                                match = "\\b(?i)(db|dw|dd|equ|org|include|macro|endm|section|segment|align|extern|global|proc|endp)\\b"
                            }
                        }
                    }
                }
            };
            
            // Serialize to JSON
            var grammarContent = JsonSerializer.Serialize(grammar, _jsonSerializerOptions);
            
            // Write to file
            File.WriteAllText(Path.Combine(syntaxesDir, "ndasm.tmLanguage.json"), grammarContent);
        }
    }
}
