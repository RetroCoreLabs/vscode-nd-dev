        /// <summary>
        /// Process ASCII table tags in description text, formatting them appropriately for VS Code display
        /// </summary>
        private string ProcessAsciiTables(string text)
        {
            if (string.IsNullOrEmpty(text))
                return text;

            // Process ASCII tables - for VS Code, we'll keep them as pre-formatted text but remove the tags
            if (text.Contains("<ascii-table>") && text.Contains("</ascii-table>"))
            {
                var regex = new System.Text.RegularExpressions.Regex("<ascii-table>(.*?)</ascii-table>", 
                    System.Text.RegularExpressions.RegexOptions.Singleline);
                
                return regex.Replace(text, match => 
                {
                    var tableContent = match.Groups[1].Value;
                    // For VS Code, simply preserve the content without the tags as pre-formatted text
                    return tableContent;
                });
            }

            return text;
        }

        private string GenerateInstructionVisualization(InstructionDefinition inst)
        {
            // If the instruction has an instruction class, use its operands
            if (!string.IsNullOrEmpty(inst.InstructionClass))
            {
                var instructionClass = Loader.GetCpuDefinition().Metadata.InstructionClasses
                    .FirstOrDefault(ic => ic.Name == inst.InstructionClass);
                    
                if (instructionClass?.Operands != null)
                {
                    return instructionClass.GeneratedBitFormat;
                }
            }

            // Use pre-generated bit format instead of generating it again
            return inst.GeneratedBitFormat ?? string.Empty;
        }

        private void CopyReadmeFile(string extensionPath)
        {
            var readmePath = GetTemplatePath(Path.Combine(TEMPLATES_RELATIVE_PATH, "README.md"));
            
            if (!File.Exists(readmePath))
            {
                // Fallback to assembly location
                var assemblyLocation = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
                if (string.IsNullOrEmpty(assemblyLocation))
                {
                    Console.WriteLine("README.md template not found, skipping...");
                    return;
                }

                readmePath = Path.Combine(assemblyLocation, "Templates", "README.md");
                
                if (!File.Exists(readmePath))
                {
                    Console.WriteLine("README.md template not found, skipping...");
                    return;
                }
            }
            
            var destReadmePath = Path.Combine(extensionPath, "README.md");
            File.Copy(readmePath, destReadmePath, overwrite: true);
        }


        private void CopyFile(string extensionPath, string fileName)
        {
            var sourceFilePath = GetTemplatePath(Path.Combine(TEMPLATES_RELATIVE_PATH, fileName));
            
            if (!File.Exists(sourceFilePath))
            {
               throw new Exception($"File {fileName} not found!");
            }
            
            var destFilePath = Path.Combine(extensionPath, fileName);
            File.Copy(sourceFilePath, destFilePath, overwrite: true);
        }


