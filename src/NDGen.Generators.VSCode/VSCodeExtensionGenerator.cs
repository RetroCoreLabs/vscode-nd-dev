        // Keep this method since it's truly dynamic and uses data from the loader
        // Generate the file "syntaxes/ndasm.tmLanguage.json"
        private void GenerateTextMateGrammarDynamically(string syntaxesDir)
        {
            // Get all instructions from the definition
            var instructions = Loader.GetInstructions().Select(i => i.Name).ToList();
            var registers = Loader.GetCpuDefinition().Metadata.Registers.Select(r => r.Name).ToList();
            
            // Define grammar for syntax highlighting
            var grammar = new
            {
                name = "ND-100 Assembly",
                scopeName = "source.ndasm",
                fileTypes = new[] { "asm", "s" },
                patterns = new[]
                {
                    new { include = "#comment" },
                    new { include = "#instruction" },
                    new { include = "#register" },
                    new { include = "#literal" },
                    new { include = "#directive" }
                },
                repository = new
                {
                    comment = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "comment.line.semicolon.ndasm",
                                match = ";.*$"
                            }
                        }
                    },
                    instruction = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "keyword.instruction.ndasm",
                                match = $"\\b(?i)({string.Join("|", instructions)})\\b"
                            }
                        }
                    },
                    register = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "variable.register.ndasm",
                                match = $"\\b(?i)({string.Join("|", registers)})\\b"
                            }
                        }
                    },
                    literal = new
                    {
                        patterns = new object[]
                        {
                            new
                            {
                                name = "constant.numeric.hex.ndasm",
                                match = "\\b0x[0-9A-Fa-f]+\\b"
                            },
                            new
                            {
                                name = "constant.numeric.binary.ndasm",
                                match = "\\b0b[01]+\\b"
                            },
                            new
                            {
                                name = "constant.numeric.decimal.ndasm",
                                match = "\\b[0-9]+\\b"
                            },
                            new
                            {
                                name = "string.quoted.double.ndasm",
                                begin = "\"",
                                end = "\"",
                                patterns = new[]
                                {
                                    new
                                    {
                                        name = "constant.character.escape.ndasm",
                                        match = "\\\\."
                                    }
                                }
                            },
                            new
                            {
                                name = "string.quoted.single.ndasm",
                                begin = "'",
                                end = "'",
                                patterns = new[]
                                {
                                    new
                                    {
                                        name = "constant.character.escape.ndasm",
                                        match = "\\\\."
                                    }
                                }
                            }
                        }
                    },
                    directive = new
                    {
                        patterns = new[]
                        {
                            new
                            {
                                name = "keyword.control.directive.ndasm",
                                match = "\\b(?i)(db|dw|dd|equ|org|include|macro|endm|section|segment|align|extern|global|proc|endp)\\b"
                            }
                        }
                    }
                }
            };
            
            // Serialize to JSON
            var grammarContent = JsonSerializer.Serialize(grammar, _jsonSerializerOptions);
            
            // Write to file
            File.WriteAllText(Path.Combine(syntaxesDir, "ndasm.tmLanguage.json"), grammarContent);
        }
